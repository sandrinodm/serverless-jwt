import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { format } from 'vite-plus/fmt';

import { messages, JwtVerifierError } from '../packages/jwt-verifier/src/errors.ts';
import {
  optionBounds,
  optionReference,
  validateOptions,
} from '../packages/jwt-verifier/src/options.ts';
import configuration from '../vite.config.ts';

/**
 * Rejects a missing or obsolete metadata entry when either public option interface changes.
 */
export function assertMetadataCoverage(source, metadata) {
  const names = [];
  for (const [name, prefix] of [
    ['JwtVerifierOptions', ''],
    ['KeyOptions', 'keys.'],
  ]) {
    const body = source.match(
      new RegExp(`export interface ${name}[^\\{]*\\{([\\s\\S]*?)^}`, 'm'),
    )?.[1];
    assert.ok(body, `Missing ${name} interface`);
    for (const match of body.matchAll(/readonly (\w+)\??:/g)) {
      names.push(prefix + match[1]);
    }
  }

  assert.deepEqual(Object.keys(metadata).sort(), names.sort(), 'Option metadata drift');
}

/**
 * Renders defaults from the implementation and errors through their actual HTTP serializer.
 */
export async function renderReferences() {
  const source = readFileSync(
    new URL('../packages/jwt-verifier/src/options.ts', import.meta.url),
    'utf8',
  );
  assertMetadataCoverage(source, optionReference);
  const defaults = validateOptions({
    issuer: 'https://issuer.example',
    audience: 'https://api.example',
  });
  const special = {
    issuer: 'required',
    audience: 'required',
    keys: 'see below',
    shareInflight: 'runtime detection',
    fetch: 'globalThis.fetch',
    mapClaims: 'verified claims',
    clock: 'Date.now',
    onDiagnostic: 'unset',
  };
  const rows = Object.entries(optionReference).map(([key, rule]) => {
    const value = key.startsWith('keys.') ? defaults.keys[key.slice(5)] : defaults[key];
    const display = special[key] ?? (value === undefined ? 'unset' : JSON.stringify(value));
    const bounds = optionBounds[key];
    const range = bounds ? ` Range: ${bounds[0]}–${bounds[1]}.` : '';
    return `| \`${key}\` | \`${display}\` | ${rule}${range} |`;
  });
  const nav =
    '[README](../README.md) · [Getting started](getting-started.md) · [Configuration](configuration.md) · [Errors](errors.md)';
  const options = `# Configuration\n\n${nav}\n\nGenerated by \`pnpm docs:reference\` from \`options.ts\` metadata and resolved defaults. Edit the implementation metadata, then regenerate. CI rejects stale output and option interfaces without metadata.\n\nCreate one verifier per trust policy and reuse it. Options are copied and frozen at construction. Durations are seconds unless stated otherwise.\n\n| Option | Default | Validation and purpose |\n| --- | --- | --- |\n${rows.join('\n')}\n\nUse [provider-specific audience and profile settings](providers/README.md). See [keys and outages](keys-and-outages.md) before enabling stale keys.\n`;
  const errors = Object.keys(messages).map((reason) => {
    const error = new JwtVerifierError(reason, { scopes: ['read:orders'] });
    const http = error.toHttp();
    return `| \`${reason}\` | \`${error.code}\` | ${http.status} | ${error.message} | \`${http.headers['www-authenticate'] ?? http.headers['retry-after'] ?? 'none'}\` |`;
  });
  const errorText = `# Errors\n\n${nav}\n\nGenerated by \`pnpm docs:reference\` from \`errors.ts\` messages and the real HTTP serializer. Every description is fixed; token values, endpoint URLs and arbitrary causes are excluded from the HTTP response.\n\n| Reason | OAuth code | Status | Fixed description | WWW-Authenticate, or Retry-After for 503 |\n| --- | --- | --- | --- | --- |\n${errors.join('\n')}\n\nMissing credentials have a bare Bearer challenge with the configured realm; they do not add an OAuth error parameter. Scope challenges contain the configured required scopes, never token input. The table uses the default realm \`api\` and an example required scope \`read:orders\`.\n\nEvery serialized error sends \`Content-Type: application/json\` and \`Cache-Control: no-store\`. A 503 sends \`Retry-After\` in seconds, rounded up and bounded to 1–30 (default 1). Server failures omit WWW-Authenticate.\n\nIntegrations await \`onError(error, platformArgs)\`. Return the platform response to override the default, or \`undefined\` for standard serialization. Consult the integration README for the exact platform arguments and response type. Before response commitment, a throwing, rejecting or unusable error-hook result selects the safe default and emits only a fixed integration diagnostic. Once a response is committed, the integration follows its documented platform error path rather than sending a second response. Do not return \`error.cause\` or log \`auth.token\`.\n\nInvalid trusted configuration throws \`ConfigurationError\` at construction; it is distinct from a rejected request. Its reason is stable and its message never echoes an invalid option.\n`;
  const result = {};
  for (const [name, content] of Object.entries({
    'configuration.md': options,
    'errors.md': errorText,
  })) {
    const formatted = await format(`docs/${name}`, content, configuration.fmt);
    assert.deepEqual(formatted.errors, []);
    result[name] = formatted.code;
  }

  return result;
}

/**
 * Checks checked-in references exactly; also usable against disposable negative-test output.
 */
export function checkReferences(directory, references) {
  for (const [name, content] of Object.entries(references)) {
    assert.equal(
      readFileSync(resolve(directory, name), 'utf8'),
      content,
      `Reference drift in ${name}; run pnpm docs:reference`,
    );
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const references = await renderReferences();
  if (process.argv.includes('--check')) {
    checkReferences('docs', references);
  } else {
    for (const [name, content] of Object.entries(references)) {
      writeFileSync(resolve('docs', name), content);
    }
  }
}
