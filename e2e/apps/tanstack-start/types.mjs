import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Native app checks use the pinned TS7 executable while public package declarations stay isolated.
 */
const root = resolve(import.meta.dirname, '../../..');
/**
 * Exact workspace compiler also belongs to every disposable selected-peer copy.
 */
const compiler = resolve(root, 'node_modules/.bin/tsc');
/**
 * Reviewable native generated-file/config evidence is regenerated by normal ready and peer checks.
 */
const output = resolve(root, 'reports/types');
mkdirSync(output, { recursive: true });
assert.match(execFileSync(compiler, ['--version'], { encoding: 'utf8' }), /^Version 7\./u);
for (const framework of ['react', 'solid']) {
  const config = 'tsconfig.' + framework + '.json';
  const run = (args) =>
    execFileSync(compiler, args, { cwd: import.meta.dirname, encoding: 'utf8', timeout: 60_000 });
  const effective = JSON.parse(run(['-p', config, '--showConfig']));
  assert.equal(effective.compilerOptions.strict, true);
  assert.equal(effective.compilerOptions.noEmit, true);
  assert.equal(effective.compilerOptions.isolatedDeclarations, false);
  const included = run(['-p', config, '--listFilesOnly']);
  for (const native of ['/src/routeTree.gen.ts', '/src/functions.ts', '/src/routes/api.me.ts']) {
    assert.ok(
      included.includes('/' + framework + native),
      'Native included app type input is missing',
    );
  }

  run(['-p', config]);
  let negative;
  if (process.argv.includes('--prove-negative')) {
    const route = resolve(import.meta.dirname, framework, 'src/routes/api.me.ts');
    const original = readFileSync(route);
    const hash = (value) => createHash('sha256').update(value).digest('hex');
    try {
      writeFileSync(
        route,
        Buffer.concat([
          original,
          Buffer.from(
            "\ncreateMiddleware({type:'request'}).middleware([third]).server(({context,next})=>{const invalid:number=context.auth.identity.subject;void invalid;return next();});\n",
          ),
        ]),
      );
      const result = spawnSync(compiler, ['-p', config], {
        cwd: import.meta.dirname,
        encoding: 'utf8',
        timeout: 60_000,
      });
      assert.ifError(result.error);
      assert.equal(result.status, 1, 'Included native context type corruption must fail');
      assert.match(result.stdout + result.stderr, /TS2322/u);
      writeFileSync(
        resolve(output, 'tanstack-' + framework + '-negative.log'),
        result.stdout + result.stderr,
      );
      negative = { exit: result.status, diagnostic: 'TS2322', before: hash(original) };
    } finally {
      writeFileSync(route, original);
    }

    assert.equal(
      hash(readFileSync(route)),
      negative.before,
      'Native route source was not restored',
    );
    run(['-p', config]);
    negative.after = hash(readFileSync(route));
  }

  writeFileSync(
    resolve(output, 'tanstack-' + framework + '-effective.json'),
    JSON.stringify(effective, null, 2) + '\n',
  );
  writeFileSync(resolve(output, 'tanstack-' + framework + '-included.txt'), included);
  if (negative) {
    writeFileSync(
      resolve(output, 'tanstack-' + framework + '-negative.json'),
      JSON.stringify(negative, null, 2) + '\n',
    );
  }
}

execFileSync(compiler, ['-p', resolve(root, 'packages/tanstack-start/tsconfig.types.json')], {
  cwd: root,
  stdio: 'inherit',
  timeout: 60_000,
});
console.log(
  'Verified TS7 native generated route/RPC types and unchanged public isolated declarations.',
);
