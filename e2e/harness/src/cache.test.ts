import {
  cpSync,
  mkdtempDisposableSync,
  mkdirSync,
  rmSync,
  readFileSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { expect, it } from 'vite-plus/test';

import { outputDigest, restoreBuildOutput } from './cache.ts';
import { applicationCacheKey } from './release.ts';

it('keys actual source and artifact bytes while ignoring generated output changes', () => {
  using directory = mkdtempDisposableSync(join(tmpdir(), 'serverless-jwt-cache-key-'));
  writeFileSync(join(directory.path, 'app.ts'), 'export const value = 1;');
  const original = applicationCacheKey(directory.path, []);
  mkdirSync(join(directory.path, 'dist'));
  writeFileSync(join(directory.path, 'dist/app.mjs'), 'generated');
  expect(applicationCacheKey(directory.path, [])).toBe(original);
  mkdirSync(join(directory.path, '.nitro'));
  writeFileSync(join(directory.path, '.nitro/routes.d.ts'), 'generated native routes');
  expect(applicationCacheKey(directory.path, [])).toBe(original);
  writeFileSync(join(directory.path, 'app.ts'), 'export const value = 2;');
  expect(applicationCacheKey(directory.path, [])).not.toBe(original);
});

it('attests generated bytes, paths and symlink targets independently of copy location', () => {
  using directory = mkdtempDisposableSync(join(tmpdir(), 'serverless-jwt-cache-bytes-'));
  const source = join(directory.path, 'source');
  const copy = join(directory.path, 'copy');
  mkdirSync(source);
  writeFileSync(join(source, 'output.mjs'), 'verified generated bytes');
  symlinkSync('output.mjs', join(source, 'entry.mjs'));
  const original = outputDigest(source);
  cpSync(source, copy, { recursive: true, verbatimSymlinks: true });
  expect(outputDigest(copy)).toBe(original);
  writeFileSync(join(copy, 'output.mjs'), 'tampered');
  expect(outputDigest(copy)).not.toBe(original);
  writeFileSync(join(copy, 'output.mjs'), 'verified generated bytes');
  rmSync(join(copy, 'entry.mjs'));
  symlinkSync('different.mjs', join(copy, 'entry.mjs'));
  expect(outputDigest(copy)).not.toBe(original);
});

it('rejects real cache corruption before replacing the destination and refuses non-output paths', () => {
  using directory = mkdtempDisposableSync(join(tmpdir(), 'serverless-jwt-cache-restore-'));
  const cache = join(directory.path, 'cache');
  const app = join(directory.path, 'app');
  mkdirSync(join(cache, 'dist'), { recursive: true });
  mkdirSync(join(app, 'dist'), { recursive: true });
  writeFileSync(join(cache, 'dist/app.mjs'), 'verified native output');
  writeFileSync(join(app, 'dist/app.mjs'), 'old destination output');
  const digest = outputDigest(join(cache, 'dist'));
  writeFileSync(join(cache, 'dist/app.mjs'), 'deliberately poisoned native output');
  expect(() => restoreBuildOutput(cache, app, 'dist', digest, ['dist'])).toThrow(
    'Cached output bytes changed',
  );
  expect(readFileSync(join(app, 'dist/app.mjs'), 'utf8')).toBe('old destination output');
  expect(() => restoreBuildOutput(cache, app, '../auth.config.ts', digest, ['dist'])).toThrow(
    'non-output path',
  );
  writeFileSync(join(cache, 'dist/app.mjs'), 'verified native output');
  restoreBuildOutput(cache, app, 'dist', digest, ['dist']);
  expect(readFileSync(join(app, 'dist/app.mjs'), 'utf8')).toBe('verified native output');
});
